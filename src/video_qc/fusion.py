"""Generate a self-contained native Fusion Lua importer with editable animation."""

from fractions import Fraction
from pathlib import Path

from .render import padded_box


def export_lua(store, path: Path, metadata: dict, config):
    width, height = metadata["width"], metadata["height"]
    fps = float(Fraction(metadata["fps"]))
    with path.open("w", encoding="utf-8") as out:
        out.write(f"""-- Generated by video-qc. Display coordinates; source time in seconds.
-- Run on matching unretimed footage. Set VIDEO_QC_OFFSET in frames for trims.
local comp = comp or composition or (fu and fu:GetCurrentComp())
assert(comp, "Open a Fusion composition first")
local offset = VIDEO_QC_OFFSET or comp:GetData("video_qc.offset") or comp:GetAttrs().COMPN_GlobalStart or 0
local fps = VIDEO_QC_FPS or comp:GetData("video_qc.fps") or {fps:.12g}
local mediaOut = comp:FindTool("MediaOut1")
assert(mediaOut, "Composition needs MediaOut1")
local input = mediaOut.Input:GetConnectedOutput()
assert(input, "MediaOut1 needs a connected image")
assert(not comp:FindTool("URLBlur_1"), "URL masks already imported; undo before importing again")
comp:Lock()
comp:StartUndo("Import URL blur tracking")
local ok, err = pcall(function()
local previous = input:GetTool()
""")
        for tid, _, _ in store.db.execute("SELECT * FROM tracks ORDER BY id"):
            out.write(f"""do
  local mask = comp:AddTool("RectangleMask", -32768, -32768)
  mask:SetAttrs({{TOOLS_Name = "URLMask_{tid}"}})
  mask.Center = comp:Path({{}})
  mask.Width = comp:BezierSpline({{}})
  mask.Height = comp:BezierSpline({{}})
  mask.Level = comp:BezierSpline({{}})
  local samples = {{
""")
            for row in store.db.execute(
                "SELECT seconds,x,y,w,h FROM samples WHERE track=? ORDER BY frame", (tid,)
            ):
                x0, y0, x1, y1 = padded_box(row[1:], width, height, config.padding)
                out.write(
                    f"    {{{row[0]:.9f}, {(x0 + x1) / 2 / width:.9f}, {1 - (y0 + y1) / 2 / height:.9f}, {(x1 - x0) / width:.9f}, {(y1 - y0) / height:.9f}}},\n"
                )
            out.write(f"""  }}
  local levels = {{}}
  local last = nil
  for _, s in ipairs(samples) do
    local t = math.floor(s[1] * fps + 0.5) + offset
    mask.Center[t] = {{s[2], s[3]}}
    mask.Width[t] = s[4]
    mask.Height[t] = s[5]
    if not last or t > last + 1 then
      levels[t-1] = {{0, Flags = {{StepIn = true}}}}
    end
    levels[t] = {{1, Flags = {{StepIn = true}}}}
    levels[t+1] = {{0, Flags = {{StepIn = true}}}}
    last = t
  end
  mask.Level:GetConnectedOutput():GetTool():SetKeyFrames(levels, true)
  local blur = comp:AddTool("Blur", -32768, -32768)
  blur:SetAttrs({{TOOLS_Name = "URLBlur_{tid}"}})
  blur:ConnectInput("Input", previous)
  blur:ConnectInput("EffectMask", mask)
  blur:SetInput("XBlurSize", {config.blur_sigma:.6g})
  blur:SetInput("YBlurSize", {config.blur_sigma:.6g})
  previous = blur
end
""")
        out.write("""mediaOut:ConnectInput("Input", previous)
end)
comp:EndUndo(true)
comp:Unlock()
if not ok then comp:Undo(); error(err) end
print("URL masks imported. Review coverage and adjust blur strength before delivery.")
""")
